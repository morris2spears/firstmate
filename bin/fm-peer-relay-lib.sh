# shellcheck shell=bash
# Shared peer-relay record, validation, and generated-check helpers.
# Source-safe; exact CLI mechanics live in the receive, poll, reply, and tell scripts.

FM_PEER_RELAY_LIB_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=bin/fm-x-lib.sh
. "$FM_PEER_RELAY_LIB_DIR/fm-x-lib.sh"

FMPEER_ORIGIN_HOST=carbon
FMPEER_CONFIG_NAME=peer-relay-carbon
# shellcheck disable=SC2034 # Public constant consumed by scripts that source this library.
FMPEER_CHECK_ID=peer-relay-watch

fmpeer_enabled() {  # <home>
  local home=$1 config flag
  config="${FM_CONFIG_OVERRIDE:-$home/config}"
  flag="$config/$FMPEER_CONFIG_NAME"
  [ -f "$flag" ] && [ ! -L "$flag" ]
}

fmpeer_request_id_valid() {  # <id>
  case "${1-}" in
    ''|.*|*[!A-Za-z0-9_-]*) return 1 ;;
  esac
  [ "${#1}" -le 64 ]
}

fmpeer_origin_host_valid() {  # <host>
  [ "${1-}" = "$FMPEER_ORIGIN_HOST" ]
}

fmpeer_pane_id_valid() {  # <tmux-pane-id>
  local rest
  case "${1-}" in %*) rest=${1#%} ;; *) return 1 ;; esac
  case "$rest" in ''|*[!0-9]*) return 1 ;; esac
}

fmpeer_window_id_valid() {  # <tmux-window-id>
  local rest
  case "${1-}" in @*) rest=${1#@} ;; *) return 1 ;; esac
  case "$rest" in ''|*[!0-9]*) return 1 ;; esac
}

fmpeer_session_name_valid() {  # <tmux-session-name>
  case "${1-}" in
    ''|*[!A-Za-z0-9_.-]*) return 1 ;;
  esac
  [ "${#1}" -le 64 ]
}

fmpeer_epoch_valid() {  # <epoch>
  case "${1-}" in
    ''|*[!0-9]*) return 1 ;;
  esac
  [ "${#1}" -le 18 ]
}

fmpeer_store_dir() {  # <state>
  printf '%s/peer-relay/requests\n' "$1"
}

fmpeer_offered_dir() {  # <state>
  printf '%s/peer-relay/offered\n' "$1"
}

fmpeer_request_dir() {  # <state> <id>
  fmpeer_request_id_valid "$2" || return 1
  printf '%s/%s\n' "$(fmpeer_store_dir "$1")" "$2"
}

fmpeer_request_dir_valid() {  # <state> <id>
  local dir device file
  dir=$(fmpeer_request_dir "$1" "$2") || return 1
  device=$(fmx_private_artifact_dir_device "$dir") || return 1
  for file in meta status message; do
    fmx_single_link_file_mode_valid "$dir/$file" 600 "$device" || return 1
  done
}

fmpeer_meta_get() {  # <request-dir> <key>
  local dir=$1 key=$2
  case "$key" in
    version|request_id|origin_host|pane_id|session_name|window_id|client_epoch|received_epoch) ;;
    *) return 1 ;;
  esac
  sed -n "s/^${key}=//p" "$dir/meta" | head -n 1
}

fmpeer_status_get() {  # <request-dir>
  sed -n 's/^state=//p' "$1/status" | head -n 1
}

fmpeer_status_write() {  # <request-dir> <state> <epoch>
  local dir=$1 state=$2 epoch=$3
  printf 'state=%s\nupdated_epoch=%s\n' "$state" "$epoch" \
    | fmx_private_artifact_publish_stdin "$dir" status 600
}

fmpeer_stat_mtime() {  # <path>
  if [ "$(uname)" = Darwin ]; then
    stat -f %m "$1" 2>/dev/null
  else
    stat -c %Y "$1" 2>/dev/null
  fi
}

fmpeer_poll_check_content() {  # <home> <root>
  local home=$1 root=$2
  printf '%s\n' \
    '#!/usr/bin/env bash' \
    '# Auto-generated by fm-bootstrap.sh - trusted peer-relay pending poll.' \
    "export FM_HOME=$(printf '%q' "$home")" \
    "exec $(printf '%q' "$root/bin/fm-peer-relay-poll.sh")"
}
